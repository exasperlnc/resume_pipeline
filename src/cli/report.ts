import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parseArgs } from "node:util";
import { openDb } from "../db.js";
import { buildMarketData } from "../market/data.js";
import { checkReportNumbers, createClaudeInterpreter } from "../market/report.js";
import { DEFAULT_TARGETS } from "../market/targets.js";

if (existsSync(".env")) process.loadEnvFile(".env");

const { values } = parseArgs({
  options: {
    out: { type: "string", default: "reports" },
    // Write the data snapshot only, without calling the model.
    "data-only": { type: "boolean", default: false },
  },
});

const db = openDb();
try {
  const data = buildMarketData(db, DEFAULT_TARGETS);
  mkdirSync(values.out, { recursive: true });
  const base = join(values.out, `market-${data.asOf}`);
  writeFileSync(`${base}.json`, JSON.stringify(data, null, 2) + "\n");
  console.log(`Wrote ${base}.json (${data.scope.extracted} postings, ${data.matchesTotal} matches)`);

  if (data.scope.notYetExtracted > 0) {
    console.warn(`Note: ${data.scope.notYetExtracted} open postings aren't extracted yet. Run npm run extract first for a complete report.`);
  }

  if (!values["data-only"]) {
    const model = process.env.REPORT_MODEL || undefined;
    const { markdown, model: used } = await createClaudeInterpreter({ model })(data);
    const unsupported = checkReportNumbers(markdown, data);
    const footer = [
      "",
      "---",
      `Generated by ${used} from \`${base}.json\`. Every figure should appear in that file.`,
      unsupported.length > 0
        ? `**Unverified numbers** (not found in the data; check before relying on them): ${unsupported.join(", ")}`
        : "All numbers in this report were found in the data snapshot.",
      "",
    ].join("\n");
    writeFileSync(`${base}.md`, markdown + "\n" + footer);
    console.log(`Wrote ${base}.md`);
    if (unsupported.length > 0) console.warn(`Unverified numbers: ${unsupported.join(", ")}`);
  }
} finally {
  db.close();
}
